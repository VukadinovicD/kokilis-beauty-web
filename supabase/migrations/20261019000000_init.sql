-- Kokilis Beauty schema, ported from the Laravel API.
-- Users live in Supabase Auth; only those with app_metadata.role = 'admin' can see or change data.

create function public.is_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin'
$$;

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Clients

create table public.clients (
  id bigint generated by default as identity primary key,
  first_name text not null check (char_length(first_name) between 1 and 255),
  last_name text not null check (char_length(last_name) between 1 and 255),
  nickname text check (char_length(nickname) <= 255),
  phone_number text not null check (char_length(phone_number) between 1 and 30),
  -- Lets search match phone numbers regardless of spaces, dashes or slashes.
  phone_digits text generated always as (regexp_replace(phone_number, '\D', '', 'g')) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger clients_set_updated_at
  before update on public.clients
  for each row execute function public.set_updated_at();

-- Salon services

create table public.salon_services (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique check (char_length(name) between 1 and 255),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create function public.set_salon_service_slug()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.slug := trim(both '-' from regexp_replace(
    lower(translate(replace(replace(new.name, 'đ', 'dj'), 'Đ', 'Dj'), 'čćšžČĆŠŽ', 'ccszCCSZ')),
    '[^a-z0-9]+', '-', 'g'
  ));
  return new;
end;
$$;

create trigger salon_services_set_slug
  before insert or update of name on public.salon_services
  for each row execute function public.set_salon_service_slug();

create trigger salon_services_set_updated_at
  before update on public.salon_services
  for each row execute function public.set_updated_at();

-- Appointments

create table public.appointments (
  id bigint generated by default as identity primary key,
  -- Local wall-clock time, exactly as the web app sends it, so no time zone.
  start_time timestamp not null,
  client_id bigint not null references public.clients on update cascade on delete cascade,
  salon_service_id bigint not null references public.salon_services on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index appointments_start_time_idx on public.appointments (start_time);
create index appointments_client_id_idx on public.appointments (client_id);
create index appointments_salon_service_id_idx on public.appointments (salon_service_id);

create trigger appointments_set_updated_at
  before update on public.appointments
  for each row execute function public.set_updated_at();

-- Access: admins only

alter table public.clients enable row level security;
alter table public.salon_services enable row level security;
alter table public.appointments enable row level security;

create policy "Admins manage clients" on public.clients
  for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

create policy "Admins manage salon services" on public.salon_services
  for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

create policy "Admins manage appointments" on public.appointments
  for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
